import pathlib
import re

root = pathlib.Path("Kondratiev Waves")

def insert_before_ref(filepath, content):
    text = filepath.read_text(encoding="utf-8")
    ref_pattern = re.compile(r'^(##?\s*(?:Academic\s+)?References|##?\s*Works\s+Cited|##?\s*Bibliography|##?\s*Primary\s+Sources|##?\s*Key\s+References)', re.MULTILINE | re.IGNORECASE)
    match = ref_pattern.search(text)
    if match:
        idx = match.start()
        new_text = text[:idx] + content + "\n\n" + text[idx:]
    else:
        new_text = text + "\n\n" + content
    filepath.write_text(new_text, encoding="utf-8")

